package aes

import "testing"

// Function TestBytestoState verifies that bytes are correctly mapped
// to its corresponding AES state matrix.
func TestBytesToState(t *testing.T) {
	bytes := [16]byte{

		0x00, 0x01, 0x02, 0x03,
		0x04, 0x05, 0x06, 0x07,
		0x08, 0x09, 0x0a, 0x0b,
		0x0c, 0x0d, 0x0e, 0x0f,
	}
	expected := State{
		{0x00, 0x04, 0x08, 0x0c},
		{0x01, 0x05, 0x09, 0x0d},
		{0x02, 0x06, 0x0a, 0x0e},
		{0x03, 0x07, 0x0b, 0x0f},
	}

	got := bytesToState(bytes)

	if got != expected {
		t.Fatalf(
			"\nexpected: %x\ngot:	%x",
			expected,
			got,
		)
	}
}

// Function TestStateToBytes verifies that AES state is correctly mapped
// to its corresponding bytes.
func TestStateToBytes(t *testing.T) {
	state := State{
		{0x00, 0x04, 0x08, 0x0c},
		{0x01, 0x05, 0x09, 0x0d},
		{0x02, 0x06, 0x0a, 0x0e},
		{0x03, 0x07, 0x0b, 0x0f},
	}
	expected := [16]byte{

		0x00, 0x01, 0x02, 0x03,
		0x04, 0x05, 0x06, 0x07,
		0x08, 0x09, 0x0a, 0x0b,
		0x0c, 0x0d, 0x0e, 0x0f,
	}

	got := stateToBytes(state)

	if got != expected {
		t.Fatalf(
			"\nexpected: %x\ngot:	%x",
			expected,
			got,
		)
	}
}
